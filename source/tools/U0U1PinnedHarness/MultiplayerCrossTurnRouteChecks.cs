using System.Reflection;
using System.Text.Json;
using CombatSolver;
using MegaCrit.Sts2.Core.Combat;
using MegaCrit.Sts2.Core.Context;

namespace U0U1PinnedHarness;

internal static class MultiplayerCrossTurnRouteChecks
{
    internal static (int Checks, int Replays) Run(CombatState live, SolverDisplayNames names,
        BattleDamageSnapshot originalDamage, SearchPolicySnapshot captured, SolverResult nativeSource, string output)
    {
        int checks = 0, replays = 0;
        List<object> rows = [];
        void Check(bool ok, string reason)
        {
            if (!ok) throw new InvalidOperationException(reason);
            checks++;
        }
        var player = LocalContext.GetMe(live)!;
        var playerState = player.PlayerCombatState!;
        var turnProperty = playerState.GetType().GetProperty("TurnNumber")!;
        int originalTurn = playerState.TurnNumber;
        var enemy = live.Enemies.Single();
        int originalHp = enemy.CurrentHp;
        BattleDamageSnapshot damage = originalDamage with { HpLostSoFar = 7, PotionsUsedSoFar = 1 };
        SearchPolicySnapshot policy = captured with
        {
            VerifyIncrementalSearch = false, MeasurePhasePerformance = true,
            MultiplayerPlanRefresh = null, RecoveryBudget = null, BudgetOverrideMilliseconds = null,
            ContinuationSeedActions = [], ContinuationRouteReplayActions = [], ContinuationRouteReplayBaseline = null,
            Interaction = null, StopAtAcceptableBattleHpLoss = true, AcceptableBattleHpLoss = 7,
        };
        SolverResult Clone(SolverResult result)
            => (SolverResult)typeof(object).GetMethod("MemberwiseClone", BindingFlags.Instance | BindingFlags.NonPublic)!
                .Invoke(result, null)!;
        void Set(SolverResult result, string name, object value)
            => typeof(SolverResult).GetProperty(name)!.SetValue(result, value);
        try
        {
            // First exercise exact continuation using checkpoints generated by the
            // actual multi-turn search, not the synthetic accounting fixture below.
            CombatRootSnapshot firstRoot = CombatRootSnapshot.Capture(live);
            CombatBeamSolver firstVerifier = new(firstRoot, names, originalDamage, captured);
            foreach (CachedContinuation cached in nativeSource.Continuations)
            {
                var prefix = firstVerifier.ReplayDiagnosticPrefix(nativeSource.BestNode.Actions
                    .Where(action => action.Turn < cached.StartTurnNumber).ToArray());
                try
                {
                    Check(firstVerifier.CaptureDiagnosticContinuation(prefix) == cached.ExpectedState,
                        "Native continuation checkpoint differs from independent prefix replay.");
                    replays++;
                    var expected = cached.MultiplayerExpectation!;
                    MultiplayerContinuationValidation actual = new(expected.CombatIdentity, expected.LocalNetId,
                        expected.MultiplayerScalingHooks, expected.CardMultiplayerConstraint, expected.SourceWorldVersion + 2,
                        expected.SourceWorldVersion + 1);
                    Check(nativeSource.TryCreateContinuation(cached.ExpectedState, cached.StartTurnNumber, prefix.PlayerHp,
                        originalDamage with { HpLostSoFar = originalDamage.HpLostSoFar + prefix.CumulativePlayerHpLost },
                        actual, out var continued, out _), "Native route could not be continued at its independently replayed checkpoint.");
                    Check(continued!.MultiplayerReplayCandidates.Count == nativeSource.MultiplayerReplayCandidates.Count
                        && continued.MultiplayerReplayCandidates.All(candidate => candidate.Route.All(action => action.Turn >= cached.StartTurnNumber)),
                        "Native continued route lost alternatives or retained already executed turns.");
                }
                finally { prefix.ReleaseSimulator(); }
            }
            Check(nativeSource.Continuations.Count >= 2, "Native checkpoint coverage did not reach two future turns.");
            // Native current-turn state, with controlled turn/HP edits. Transported
            // history is synthetic: this does not claim a native EndTurn/Controller run.
            int turn = originalTurn + 1;
            turnProperty.SetValue(playerState, turn);
            CombatRootSnapshot root = CombatRootSnapshot.Capture(live);
            SolverResult fresh = CombatSearchCoordinator.Solve(root, names, damage, policy,
                CancellationToken.None, null);
            Check(fresh.MultiplayerReplayCandidates.Count == 3, "Turn-two fixture needs three native full routes.");
            PlanAction[] history = [new(PlanActionKind.UsePotion, originalTurn, PotionId: "PAST_FIXTURE_POTION"),
                new(PlanActionKind.EndTurn, originalTurn)];
            SolverResult retained = Clone(fresh);
            Set(retained, nameof(SolverResult.StartTurnNumber), originalTurn);
            PlanAction[] full = [.. history, .. fresh.BestNode.Actions];
            Set(retained, nameof(SolverResult.BestNode), new SelectedSearchPlan(full, full.Length, fresh.BestNode.Score));
            retained.MultiplayerReplayCandidates = Array.AsReadOnly(fresh.MultiplayerReplayCandidates.Select(candidate =>
                candidate with { Route = Array.AsReadOnly<PlanAction>([.. history, .. candidate.Route]) }).ToArray());
            Set(retained, nameof(SolverResult.PotionCountByTurn), new Dictionary<int, int> { [originalTurn] = 1 });
            Set(retained, nameof(SolverResult.PotionStrategicCostByTurn), new Dictionary<int, int> { [originalTurn] = 9 });
            MultiplayerContinuationExpectation expectation = new("fixture-combat", "1", true, "local", 1);
            MultiplayerContinuationValidation validation = new("fixture-combat", "1", true, "local", 3, 2);
            Set(retained, nameof(SolverResult.Continuations), new[] { new CachedContinuation(root.ContinuationStamp, turn, 0, expectation) });
            Check(retained.TryCreateContinuation(root.ContinuationStamp, turn, player.Creature.CurrentHp, damage,
                validation, out var reused, out _), "Exact continuation rejected the matched frozen fixture.");
            Check(reused!.MultiplayerReplayCandidates.Count == 3
                && reused.MultiplayerReplayCandidates.All(candidate => candidate.Route.All(action => action.Turn >= turn)
                    && candidate.Prefix.All(action => action.Turn == turn)), "Exact reuse lost or failed to slice full alternatives.");
            Check(reused.PotionCount == 0 && reused.PotionHpRequired == 0
                && reused.ProjectedBattleHpLost == fresh.ProjectedBattleHpLost,
                "Exact reuse charged a completed potion or battle loss twice.");
            Check(!retained.TryCreateContinuation(root.ContinuationStamp, turn, player.Creature.CurrentHp, damage,
                validation with { LocalNetId = "other" }, out _, out _), "Candidate retention bypassed player identity.");
            Check(!retained.TryCreateContinuation(root.ContinuationStamp, turn, player.Creature.CurrentHp, damage,
                validation with { CurrentWorldVersion = 2 }, out _, out _), "Candidate retention bypassed world advancement.");
            MultiplayerPlanRefreshRequest request = MultiplayerPlanRefreshRequest.CaptureContinuation(retained, turn);
            Check(request.IsCrossTurn && request.Route.All(action => action.Turn >= turn)
                && request.Candidates.All(candidate => candidate.Route.All(action => action.Turn >= turn))
                && request.Baseline!.ProjectedBattleHpLost == fresh.ProjectedBattleHpLost,
                "Cross-turn capture changed the absolute quality ceiling or retained elapsed actions.");
            // This fixture prepends synthetic history to a result first evaluated at
            // turn two. Use the verified turn-two window for the recovery trials.
            // Capture cannot reconstruct an evaluation window at the synthetic root.
            Check(request.EvaluationWindow == null && fresh.EvaluationWindow is { CoversTarget: true },
                "Synthetic history must not manufacture an earlier evaluation window.");
            request = request with { EvaluationWindow = fresh.EvaluationWindow };
            MultiplayerPlanRefreshRequest afterReuse = MultiplayerPlanRefreshRequest.Capture(reused);
            Check(!afterReuse.IsCrossTurn && afterReuse.Route.All(action => action.Turn >= turn)
                && afterReuse.Candidates.Count == 3, "Same-turn refresh after exact reuse resurrected historical actions.");

            SolverResult Run(string name, CombatRootSnapshot frozen, MultiplayerPlanRefreshRequest suggestion,
                Action<string>? diagnostic = null, SearchPolicySnapshot? settings = null)
            {
                SolverResult result = CombatSearchCoordinator.Solve(frozen, names, damage, (settings ?? policy) with
                {
                    MultiplayerPlanRefresh = suggestion,
                    Diagnostics = new SearchDiagnosticsSink(diagnostic ?? (_ => { }), _ => { }),
                }, CancellationToken.None, null);
                CombatBeamSolver verifier = new(frozen, names, damage, policy);
                var replay = verifier.ReplayDiagnosticPrefix(result.BestNode.Actions);
                try
                {
                    Check(verifier.CaptureDiagnosticContinuation(replay) == result.PredictedFinalState
                        && damage.HpLostSoFar + replay.CumulativePlayerHpLost == result.ProjectedBattleHpLost,
                        $"{name}: fresh-root route or battle-loss accounting differs from independent replay.");
                    replays++;
                }
                finally { replay.ReleaseSimulator(); }
                Check(result.BestNode.Actions.All(action => action.Turn >= turn)
                    && result.ResultScope == SolverResultScope.SearchCompletion
                    && result.PotionCount == 0 && result.PotionHpRequired == 0,
                    $"{name}: past potion/action or old execution authority escaped transport.");
                var work = result.RequestPhaseMetrics!;
                Check(result.RecoveryBudgetMetrics!.ExpandedNodes == work.ExpandedNodes
                    && work.Members.Sum(member => (long)member.Work.TransitionCount) == work.LogicalTransitions,
                    $"{name}: cross-turn work escaped the request ledger.");
                rows.Add(new { name, result.PlanRefresh, result.TotalExpandedNodes, result.TotalTransitionCount,
                    result.ProjectedBattleHpLost, result.StartTurnNumber, result.CombatEndedTurn });
                return result;
            }
            SolverResult restored = Run("cross-turn-all-routes", root, request);
            Check(restored.PlanRefresh is { IsCrossTurn: true, WholeRouteReplayed: true, SelectedOriginalRank: 0 }
                && restored.PlanRefresh.FullRoutes.Count == 3 && restored.TotalExpandedNodes == 0,
                "Cross-turn capture did not compare all complete routes under the original horizon.");
            SolverResult refreshed = Run("same-turn-after-exact-reuse", root, afterReuse);
            Check(refreshed.PlanRefresh!.WholeRouteReplayed && refreshed.TotalExpandedNodes == 0,
                "Same-turn refresh of a continued result restarted the search.");
            PlanAction invalid = request.Route[0] with { CardId = "NONEXISTENT_FIXTURE_CARD", CardStateKey = "missing" };
            SolverResult alternative = Run("cross-turn-current-invalid", root, request with { Route = [invalid] });
            Check(alternative.PlanRefresh!.SelectedOriginalRank > 0 && alternative.TotalExpandedNodes == 0,
                "Cross-turn current failure prevented a complete alternative from recovering.");
            bool delayed = false;
            SolverResult deadline = Run("cross-turn-shared-600ms", root, request, message =>
            {
                if (delayed || !message.Contains("MP_LOCAL_XTURN_ROUTE_REPLAY status=", StringComparison.Ordinal)) return;
                delayed = true; Thread.Sleep(610);
            });
            Check(delayed && deadline.PlanRefresh!.SelectedOriginalRank == 0
                && deadline.PlanRefresh.FullRoutes.Any(row => row.Outcome == "recovery_budget_exhausted")
                && deadline.RequestPhaseMetrics!.Members.Count(member => member.Kind == nameof(SearchRequestMemberKind.RouteReplay)) == 1,
                "Cross-turn alternatives each received a separate 600ms allowance.");
            // Prove the larger existing cross-turn share is used, not the same-turn 60ms share.
            delayed = false;
            SolverResult after60 = Run("cross-turn-not-same-turn-budget", root, request, message =>
            {
                if (delayed || !message.Contains("MP_LOCAL_XTURN_ROUTE_REPLAY status=", StringComparison.Ordinal)) return;
                delayed = true; Thread.Sleep(65);
            });
            Check(after60.PlanRefresh!.FullRoutes.Count == 3
                && after60.PlanRefresh.FullRoutes.All(row => row.AcceptedActions > 0),
                "Cross-turn recovery incorrectly used the same-turn 60ms allowance.");
            MultiplayerPlanRefreshRequest allBroken = request with
            {
                Route = [invalid], Candidates = request.Candidates.Select(candidate => candidate with { Route = [invalid] }).ToArray(),
            };
            SolverResult fallback = Run("cross-turn-all-rejected", root, allBroken);
            Check(fallback.PlanRefresh is { WholeRouteReplayed: false, PrefixMetrics: null }
                && fallback.TotalExpandedNodes > 0, "Failed cross-turn recovery used the same-turn prefix path or suppressed ordinary search.");
            foreach (int dop in new[] { 1, 4 })
            {
                SearchPolicySnapshot seeded = policy with
                {
                    Profile = policy.Profile with { MaxExpandedNodes = 40 }, MaxDegreeOfParallelism = dop,
                    ContinuationSeedActions = request.Candidates[0].Prefix,
                };
                seeded = seeded with { R0TransitionPolicyIdentity = CombatTransitionMemo.CapturePolicyIdentity(seeded) };
                SolverResult repaired = Run($"cross-turn-r1-after-rejection-dop-{dop}", root, allBroken, settings: seeded);
                Check(repaired.TotalExpandedNodes <= 40 && repaired.RequestPhaseMetrics!.Members.Any(member =>
                        member.Kind == nameof(SearchRequestMemberKind.ContinuationSeed)),
                    "Cross-turn full-route failure lost R1 or allocated another full node budget.");
            }

            enemy.SetCurrentHpInternal(6);
            CombatRootSnapshot lethal = CombatRootSnapshot.Capture(live);
            var attack = request.Candidates.First(candidate => candidate.Route[0].CardId is "BASH" or "STRIKE_IRONCLAD")
                with { OriginalRank = 1 };
            SolverResult won = Run("cross-turn-victory-truncates-tail", lethal, request with { Route = [invalid], Candidates = [attack] });
            Check(won.Snapshot.AllEnemiesDead && won.ProjectedBattleHpLost == 7 && won.BestNode.ActionCount == 1
                && won.TotalExpandedNodes == 0, "Fresh-root victory failed to truncate history/tail or double-counted sunk HP.");
            Check(retained.BestNode.Actions.Count == full.Length && retained.MultiplayerReplayCandidates.All(candidate =>
                candidate.Route[0].Kind == PlanActionKind.UsePotion), "Transport mutated the retained source.");
        }
        finally
        {
            turnProperty.SetValue(playerState, originalTurn);
            enemy.SetCurrentHpInternal(originalHp);
        }
        File.WriteAllText(Path.Combine(output, "multiplayer-cross-turn-routes.json"), JsonSerializer.Serialize(new
        {
            status = "PASS", checks, independent_replays = replays,
            evidence = "native search checkpoints independently replayed; native turn-two root with controlled turn/HP and synthetic accounting history; no native EndTurn/Controller/network/UI",
            rows,
        }, new JsonSerializerOptions { WriteIndented = true }));
        return (checks, replays);
    }
}
